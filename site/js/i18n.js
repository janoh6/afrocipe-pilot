var LANG_NAMES = { en: "English", fr: "Français", sw: "Kiswahili" };
var LANG_KEY = "afrocipe-pilot-lang";

function getLang() {
  var l = null;
  try { l = new URLSearchParams(location.search).get("lang"); } catch (e) { /* ignore */ }
  if (l && DICT[l]) { setLang(l); return l; }
  try { l = localStorage.getItem(LANG_KEY); } catch (e) { l = null; }
  if (l && DICT[l]) return l;
  var n = (navigator.language || "en").slice(0, 2).toLowerCase();
  return DICT[n] ? n : "en";
}

function setLang(l) {
  if (!DICT[l]) return;
  try { localStorage.setItem(LANG_KEY, l); } catch (e) { /* storage may be blocked */ }
}

function t(lang, key, vars) {
  var s = (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
  if (vars) for (var k in vars) s = s.split("{" + k + "}").join(String(vars[k]));
  return s;
}
